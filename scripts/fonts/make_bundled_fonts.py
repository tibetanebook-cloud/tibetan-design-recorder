"""Writes src/renderer/src/bundledFonts.ts from the Fontsource packages listed below
(all SIL OFL 1.1). Run: python scripts/fonts/make_bundled_fonts.py"""
import pathlib, re
root = pathlib.Path(__file__).resolve().parents[2]
nm = root / "node_modules/@fontsource"
tibetan = ["noto-serif-tibetan", "jomolhari", "uchen"]
latin = ["inter", "roboto", "open-sans", "montserrat", "lato", "poppins", "noto-sans", "noto-serif", "merriweather",
         "playfair-display", "oswald", "raleway", "bebas-neue", "lobster", "pacifico", "dancing-script", "caveat", "source-code-pro"]
imports, tib_names, lat_names = [], [], []
for pkg in tibetan + latin:
    d = nm / pkg
    fam = re.search(r"font-family: '([^']+)'", (d / "400.css").read_text(encoding="utf-8")).group(1)
    for w in ("400", "700"):
        # Tibetan fonts: every subset (Tibetan + Latin); others: Latin only (smaller).
        name = f"{w}.css" if pkg in tibetan else f"latin-{w}.css"
        if (d / name).exists():
            imports.append(f'import "@fontsource/{pkg}/{name}";')
    (tib_names if pkg in tibetan else lat_names).append(fam)

src = f'''/**
 * Free fonts bundled with the app (SIL Open Font License 1.1, via Fontsource; see
 * docs/THIRD_PARTY.md). Every user has these, whatever is installed on their computer.
 * Generated by scripts/fonts/make_bundled_fonts.py (edit the lists there and re-run);
 * Tibetan fonts carry all subsets, the others Latin only.
 */
{chr(10).join(imports)}

/** Tibetan fonts included with the app. */
export const BUNDLED_TIBETAN_FONTS = {tib_names!r};
/** English (Latin) fonts included with the app. */
export const BUNDLED_LATIN_FONTS = {lat_names!r};
export const BUNDLED_FONTS = [...BUNDLED_TIBETAN_FONTS, ...BUNDLED_LATIN_FONTS];

/** Load every bundled font now, so text is drawn in the right face the first time. */
export async function preloadBundledFonts(): Promise<void> {{
  await Promise.all(
    BUNDLED_FONTS.flatMap((f) => ["400", "700"].map((w) => document.fonts.load(`${{w}} 48px "${{f}}"`, BUNDLED_TIBETAN_FONTS.includes(f) ? "བོད་ཡིག Aa" : "Aa").catch(() => []))),
  );
}}
'''.replace("['", '["').replace("']", '"]').replace("', '", '", "')
(root / "src/renderer/src/bundledFonts.ts").write_text(src, encoding="utf-8")
print(len(imports), tib_names, lat_names)
